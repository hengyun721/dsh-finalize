/**
 * Smoke tests for lib/office.js.
 *
 * Fixtures are built in memory with the module's own writeZip, so the suite has
 * no files on disk and no dependency. Run with `npm test` (in-process, works in
 * sandboxed terminals that cannot spawn child processes).
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { finalizeOdf, finalizeDocx, inspectPdf, readZip, writeZip } from '../lib/office.js'

const ODF_CONTENT = `<?xml version="1.0" encoding="UTF-8"?>
<office:document-content xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0" office:version="1.2">
<office:body><office:text><text:p>你好 world</text:p><text:p>second</text:p></office:text></office:body></office:document-content>`

const ODF_META = `<?xml version="1.0" encoding="UTF-8"?>
<office:document-meta xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:meta="urn:oasis:names:tc:opendocument:xmlns:meta:1.0" xmlns:dc="http://purl.org/dc/elements/1.1/" office:version="1.2">
<office:meta><meta:generator>LibreOffice/7.6.4.1$Windows_X86_64</meta:generator>
<dc:creator>python-docx</dc:creator><meta:initial-creator>python-docx</meta:initial-creator>
<meta:creation-date>2026-10-01T09:00:00</meta:creation-date><dc:date>2026-10-01T09:00:00</dc:date>
<meta:editing-duration>PT0S</meta:editing-duration><meta:editing-cycles>1</meta:editing-cycles>
<meta:document-statistic meta:page-count="1" meta:word-count="0" meta:character-count="0" meta:paragraph-count="0"/>
</office:meta></office:document-meta>`

const ODF_MANIFEST = `<?xml version="1.0" encoding="UTF-8"?>
<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">
<manifest:file-entry manifest:full-path="/" manifest:media-type="application/vnd.oasis.opendocument.text"/>
<manifest:file-entry manifest:full-path="meta.xml" manifest:media-type="text/xml"/>
<manifest:file-entry manifest:full-path="Thumbnails/thumbnail.png" manifest:media-type="image/png"/>
</manifest:manifest>`

function buildOdt() {
  return writeZip([
    { name: 'mimetype', data: Buffer.from('application/vnd.oasis.opendocument.text') },
    { name: 'content.xml', data: Buffer.from(ODF_CONTENT) },
    { name: 'meta.xml', data: Buffer.from(ODF_META) },
    { name: 'META-INF/manifest.xml', data: Buffer.from(ODF_MANIFEST) },
    { name: 'Thumbnails/thumbnail.png', data: Buffer.from([0x89, 0x50, 0x4e, 0x47]) },
  ])
}

test('odf: strips generator, recomputes statistics, drops thumbnail, keeps mimetype stored first', () => {
  const result = finalizeOdf(buildOdt(), 'odt', { author: '' })
  const entries = readZip(result.bytes)
  assert.equal(entries[0].name, 'mimetype')
  const meta = entries.find((entry) => entry.name === 'meta.xml').data.toString('utf8')
  assert.ok(!meta.includes('<meta:generator>'))
  assert.match(meta, /meta:word-count="4"/)
  assert.ok(!entries.some((entry) => entry.name === 'Thumbnails/thumbnail.png'))
  assert.ok(result.report.unresolved.some((item) => item.item === '编辑时长'))
})

const DOCX_DOCUMENT = `<?xml version="1.0" encoding="UTF-8"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>Hello 世界</w:t></w:r></w:p></w:body></w:document>`

const DOCX_CORE = `<?xml version="1.0" encoding="UTF-8"?>
<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"><dc:creator>python-docx</dc:creator><dc:description>generated by python-docx</dc:description><dcterms:created xsi:type="dcterms:W3CDTF">2013-12-23T23:15:00Z</dcterms:created></cp:coreProperties>`

const DOCX_APP = `<?xml version="1.0" encoding="UTF-8"?>
<Properties><Application>Microsoft Macintosh Word</Application><AppVersion>14.0000</AppVersion><Words>0</Words><Characters>0</Characters><Pages>1</Pages><TotalTime>0</TotalTime></Properties>`

function buildDocx() {
  return writeZip([
    { name: '_rels/.rels', data: Buffer.from('<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/thumbnail" Target="docProps/thumbnail.jpeg"/></Relationships>') },
    { name: 'word/document.xml', data: Buffer.from(DOCX_DOCUMENT) },
    { name: 'docProps/core.xml', data: Buffer.from(DOCX_CORE) },
    { name: 'docProps/app.xml', data: Buffer.from(DOCX_APP) },
    { name: 'docProps/thumbnail.jpeg', data: Buffer.from([0xff, 0xd8, 0xff, 0xd9]) },
  ])
}

test('docx: clears generator, removes Application, recomputes counts', () => {
  const result = finalizeDocx(buildDocx(), { author: '' })
  const entries = readZip(result.bytes)
  const core = entries.find((entry) => entry.name === 'docProps/core.xml').data.toString('utf8')
  const app = entries.find((entry) => entry.name === 'docProps/app.xml').data.toString('utf8')
  const rels = entries.find((entry) => entry.name === '_rels/.rels').data.toString('utf8')
  assert.match(core, /<dc:creator\s*\/?>/)
  assert.ok(!/generated by python-docx/.test(core))
  assert.ok(!app.includes('<Application>'))
  assert.match(app, /<Words>3<\/Words>/)
  assert.ok(!rels.includes('thumbnail'))
  assert.ok(result.report.unresolved.some((item) => item.item === '编辑时间'))
})

test('pdf: reports producer and incremental updates without rewriting', () => {
  const pdf = Buffer.from('%PDF-1.4\n1 0 obj\n<< /Producer (Skia/PDF m120) /Creator (Chrome) >>\nendobj\n%%EOF\n%%EOF\n', 'latin1')
  const result = inspectPdf(pdf)
  assert.equal(result.bytes, pdf)
  assert.ok(result.report.notes.some((item) => item.detail.includes('Skia/PDF')))
  assert.ok(result.report.unresolved.some((item) => item.item === '增量更新'))
})

test('a non-zip buffer is rejected instead of silently passing', () => {
  assert.throws(() => finalizeOdf(Buffer.from('x'), 'odt', {}), /not a zip container/)
})
